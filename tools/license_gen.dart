// Smart Dukan licence generator (spec Section 2). Runs on the SELLER's
// laptop only. The private key never goes into the app, the Git repository
// or any cloud folder: it lives in tools/keys/ (git-ignored) plus an offline
// backup.
//
//   dart run tools/license_gen.dart init
//       Creates tools/keys/license_private.key and writes the matching public
//       key into lib/core/security/license_public_key.dart. Rebuild the app
//       afterwards. Run ONCE; re-running replaces the key and invalidates
//       every code issued before.
//
//   dart run tools/license_gen.dart issue --device K7QM2-XPA9D-... [--pack mobile_pro]
//       [--buyer 03001234567] [--id L-0007] [--transfer-from L-0003]
//       Prints the activation code, the smartdukan:// link and a WhatsApp
//       message, and appends a row to tools/keys/sales_register.csv.
//
//   dart run tools/license_gen.dart verify --device ... --code ...
// ignore_for_file: avoid_print

import 'dart:convert';
import 'dart:io';

import 'package:cryptography/cryptography.dart';

const keyDir = 'tools/keys';
const privateKeyFile = '$keyDir/license_private.key';
const registerFile = '$keyDir/sales_register.csv';
const publicKeyDart = 'lib/core/security/license_public_key.dart';

Future<void> main(List<String> args) async {
  if (args.isEmpty) return usage();
  final opts = <String, String>{};
  for (var i = 1; i < args.length - 1; i += 2) {
    if (args[i].startsWith('--')) opts[args[i].substring(2)] = args[i + 1];
  }
  switch (args.first) {
    case 'init':
      await init(force: args.contains('--force'));
    case 'issue':
      await issue(opts);
    case 'verify':
      await verifyCmd(opts);
    default:
      usage();
  }
}

void usage() {
  print('Usage: dart run tools/license_gen.dart init | issue --device CODE [--pack mobile_pro] '
      '[--buyer PHONE] [--id ID] [--transfer-from OLD_ID] | verify --device CODE --code CODE');
  exitCode = 64;
}

Future<void> init({bool force = false}) async {
  final f = File(privateKeyFile);
  if (await f.exists() && !force) {
    print('A private key already exists at $privateKeyFile. Use "init --force" to replace it '
        '(all earlier codes stop working).');
    exitCode = 1;
    return;
  }
  final pair = await Ed25519().newKeyPair();
  final seed = await pair.extractPrivateKeyBytes();
  final pub = (await pair.extractPublicKey()).bytes;
  await Directory(keyDir).create(recursive: true);
  await f.writeAsString(base64.encode(seed));
  await File(publicKeyDart).writeAsString(publicKeyFile(pub));
  print('Private key saved to $privateKeyFile — back it up OFFLINE (USB) now.');
  print('Public key written to $publicKeyDart — rebuild the app.');
}

String publicKeyFile(List<int> pub) => '''/// Ed25519 public key that verifies licence codes (spec Section 2).
/// Generated by `dart run tools/license_gen.dart init`. The matching private
/// key is only on the seller's laptop.
const List<int> licensePublicKey = [${pub.join(', ')}];
''';

String normalize(String code) => code
    .toUpperCase()
    .replaceAll(RegExp(r'[\s-]'), '')
    .replaceAll('O', '0')
    .replaceAll(RegExp('[IL]'), '1');

String b64url(List<int> b) => base64Url.encode(b).replaceAll('=', '');

Future<void> issue(Map<String, String> o) async {
  final device = normalize(o['device'] ?? '');
  if (!RegExp(r'^[0-9A-HJKMNP-TV-Z]{26}$').hasMatch(device)) {
    print('Device Code must be 26 characters (Crockford base32).');
    exitCode = 1;
    return;
  }
  final pack = o['pack'] ?? 'mobile_pro';
  final f = File(privateKeyFile);
  if (!await f.exists()) {
    print('No private key. Run "init" first.');
    exitCode = 1;
    return;
  }
  final seed = base64.decode((await f.readAsString()).trim());
  final pair = await Ed25519().newKeyPairFromSeed(seed);
  final date = DateTime.now().toIso8601String().substring(0, 10);
  final id = o['id'] ?? 'L-${DateTime.now().millisecondsSinceEpoch.toRadixString(36).toUpperCase()}';
  final payload = 'SD1|$device|$pack|$date|$id';
  final sig = await Ed25519().sign(utf8.encode(payload), keyPair: pair);
  final code = '${b64url(utf8.encode(payload))}.${b64url(sig.bytes)}';
  final link = 'smartdukan://activate?c=$code';

  final reg = File(registerFile);
  if (!await reg.exists()) await reg.writeAsString('license_id,device_code,pack,buyer_phone,date,transfer_from\n');
  await reg.writeAsString('$id,$device,$pack,${o['buyer'] ?? ''},$date,${o['transfer-from'] ?? ''}\n', mode: FileMode.append);

  print('Licence ID : $id');
  print('Code       : $code');
  print('Link       : $link');
  print('');
  print('WhatsApp message:');
  print('Assalam o Alaikum! Aapka Smart Dukan Mobile Shop Pro tayyar hai. Is link ko tap karein: $link');
}

Future<void> verifyCmd(Map<String, String> o) async {
  final f = File(publicKeyDart).readAsStringSync();
  final m = RegExp(r'\[([0-9, ]+)\]').firstMatch(f);
  final pub = m![1]!.split(',').map((s) => int.parse(s.trim())).toList();
  final code = o['code']!;
  final dot = code.indexOf('.');
  final payload = base64Url.decode(base64Url.normalize(code.substring(0, dot)));
  final sig = base64Url.decode(base64Url.normalize(code.substring(dot + 1)));
  final ok = await Ed25519().verify(payload,
      signature: Signature(sig, publicKey: SimplePublicKey(pub, type: KeyPairType.ed25519)));
  final parts = utf8.decode(payload).split('|');
  print('Signature ${ok ? 'VALID' : 'INVALID'}; device ${parts[1] == normalize(o['device'] ?? '') ? 'matches' : 'DOES NOT match'}');
}
